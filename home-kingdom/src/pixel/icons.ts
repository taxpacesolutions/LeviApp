const cache = new Map<string, Grid>();
export function icon(name: string): Grid {
  const key = RAW[name] ? name : "scroll";
  let g = cache.get(key);
  if (!g) {
    g = outline(rows(RAW[key]));
    cache.set(key, g);
  }
  return g;
}

export const ICON_NAMES = Object.keys(RAW);
